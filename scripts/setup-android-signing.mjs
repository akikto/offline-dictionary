#!/usr/bin/env node
/**
 * Installs the Play Console upload keystore for local/CI signing.
 *
 * Usage:
 *   node scripts/setup-android-signing.mjs [path/to/signing.keystore]
 *
 * Defaults to ./signing.keystore then android/signing.keystore.
 * Writes android/keystore.properties (gitignored) and copies the keystore to
 * android/android.keystore (gitignored).
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const androidDir = path.join(root, 'android');

export const PLAY_UPLOAD_SHA1 =
  '24:7A:A9:16:C7:B3:60:7F:66:59:84:B8:84:4F:06:19:A0:B9:EA:0A';
export const PLAY_UPLOAD_SHA256 =
  '49:56:54:FE:B4:3D:BF:37:1E:3C:A5:A2:56:9C:22:58:11:1D:64:B3:41:CC:44:2B:38:4B:B0:92:8C:71:BA:D5';

const DEFAULT_ALIAS = process.env.ANDROID_KEY_ALIAS || 'my-key-alias';
const DEFAULT_STORE_PASSWORD =
  process.env.ANDROID_KEYSTORE_PASSWORD || 'lFxktJyrrrUA';
const DEFAULT_KEY_PASSWORD = process.env.ANDROID_KEY_PASSWORD || DEFAULT_STORE_PASSWORD;

function normalizeFingerprint(value) {
  return value.replace(/[^0-9A-F]/gi, '').toUpperCase();
}

function resolveSourceKeystore(argPath) {
  const candidates = [
    argPath,
    process.env.SIGNING_KEYSTORE_PATH,
    path.join(root, 'signing.keystore'),
    path.join(androidDir, 'signing.keystore'),
  ].filter(Boolean);

  for (const candidate of candidates) {
    const resolved = path.resolve(root, candidate);
    if (fs.existsSync(resolved)) {
      return resolved;
    }
  }

  console.error(
    '[setup-android-signing] Upload keystore not found.\n' +
      '  Place PWABuilder/AI Studio signing.keystore in the repo root, then run:\n' +
      '    node scripts/setup-android-signing.mjs ./signing.keystore',
  );
  process.exit(1);
}

function verifyKeystore(keystorePath, storePassword, alias) {
  const out = execFileSync(
    'keytool',
    ['-list', '-v', '-keystore', keystorePath, '-storepass', storePassword, '-alias', alias],
    { encoding: 'utf8' },
  );

  const sha1Match = out.match(/SHA1:\s*([0-9A-F:]+)/i);
  const sha256Match = out.match(/SHA256:\s*([0-9A-F:]+)/i);
  const sha1 = sha1Match?.[1] ?? null;
  const sha256 = sha256Match?.[1] ?? null;

  if (!sha1 || !sha256) {
    console.error('[setup-android-signing] Could not read certificate fingerprints from keystore.');
    process.exit(1);
  }

  const sha1Ok = normalizeFingerprint(sha1) === normalizeFingerprint(PLAY_UPLOAD_SHA1);
  const sha256Ok =
    normalizeFingerprint(sha256) === normalizeFingerprint(PLAY_UPLOAD_SHA256);

  console.log(`[setup-android-signing] Keystore SHA1:   ${sha1}`);
  console.log(`[setup-android-signing] Expected SHA1:   ${PLAY_UPLOAD_SHA1}`);
  console.log(`[setup-android-signing] Keystore SHA256: ${sha256}`);
  console.log(`[setup-android-signing] Expected SHA256: ${PLAY_UPLOAD_SHA256}`);

  if (!sha1Ok || !sha256Ok) {
    console.error(
      '[setup-android-signing] Fingerprint mismatch — this is not the Play upload key.',
    );
    process.exit(1);
  }

  console.log('[setup-android-signing] Upload key fingerprints match Play Console.');
}

function main() {
  const source = resolveSourceKeystore(process.argv[2]);
  const targetKeystore = path.join(androidDir, 'android.keystore');
  const propertiesPath = path.join(androidDir, 'keystore.properties');

  fs.mkdirSync(androidDir, { recursive: true });
  fs.copyFileSync(source, targetKeystore);

  verifyKeystore(targetKeystore, DEFAULT_STORE_PASSWORD, DEFAULT_ALIAS);

  const lines = [
    '# Generated by scripts/setup-android-signing.mjs — do not commit',
    'RELEASE_STORE_FILE=android.keystore',
    `RELEASE_STORE_PASSWORD=${DEFAULT_STORE_PASSWORD}`,
    `RELEASE_KEY_ALIAS=${DEFAULT_ALIAS}`,
    `RELEASE_KEY_PASSWORD=${DEFAULT_KEY_PASSWORD}`,
    '',
  ];
  fs.writeFileSync(propertiesPath, lines.join('\n'));

  console.log(`[setup-android-signing] Installed ${targetKeystore}`);
  console.log(`[setup-android-signing] Wrote ${propertiesPath}`);
  console.log('[setup-android-signing] Run: npm run android:package');
}

main();
